// Writes palette.json and shapes.json from the neon JS, so the Swift app reads the same
// values the mocks draw with. Run from the repo root: node design/neon/export.js
// neon.test.js fails if the JSON files are out of date.

const fs = require("fs"), path = require("path");
const core = require("./neon-core.js"), cards = require("./neon-cards.js"), maze = require("./neon-maze.js");

function build() {
  const { P } = core;
  const palette = {
    name: "Neon (vector arcade)", version: "1", date: "2026-11-14",
    note: "Generated by export.js from neon-core.js, neon-cards.js and neon-maze.js. Don't edit by hand. Card values are in the 50 x 70 card box; maze values are fractions of the cell.",
    colours: { ...P, suit: { ...P.suit }, joker: { ...P.joker }, tokens: [...P.tokens] },
    contrast: { textOnFace: 4.5, graphicOnBg: 3 },
    card: cards.M,
    maze: { ...maze.S },
    fonts: { numbers: "Russo One", ui: "Saira Semi Condensed" },
  };
  const shapes = {
    note: "Generated by export.js. Path data in a 20 x 20 box. mode fill or stroke; w is the stroke width in box units; tint main is the asset's colour, otherwise a key in palette.json colours.",
    box: 20, shapes: core.SHAPES,
  };
  return { "palette.json": JSON.stringify(palette, null, 2) + "\n", "shapes.json": JSON.stringify(shapes, null, 2) + "\n" };
}

if (require.main === module) {
  for (const [f, s] of Object.entries(build())) fs.writeFileSync(path.join(__dirname, f), s);
  console.log("Wrote palette.json and shapes.json");
}
module.exports = { build };
